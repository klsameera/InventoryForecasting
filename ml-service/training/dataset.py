"""Feature engineering and dataset construction.

Reads the CSV that Laravel's `app:export-ml-training-data` writes
(`storage/app/ml/training_data.csv`) and turns it into the
`TimeSeriesDataSet` objects DeepAR and the TFT train against. The column
contract is defined on the Laravel side in
`domain/Services/MlTrainingDataService/MlTrainingDataService.php` — the two
must change together.

On calendar features and leakage
-------------------------------
The synthetic history these models train on is generated by
`HistoricalTransactionSeeder`, which applies known festival and day-of-week
multipliers. The features below deliberately supply only *calendar facts* —
what day of the week it is, what month, whether the date falls in a known Sri
Lankan festival window — and never the seeder's effect sizes. That line
matters: a retailer genuinely knows its own holiday calendar in advance, so
these are legitimate known-future covariates that any real deployment would
build; the multipliers are what the model has to learn for itself.

On censored demand
------------------
`sold_qty` is what was *sold*, not what was *demanded*. On a stockout day the
two differ, and the target is censored downward. Rather than silently train on
that bias, `stockout_minutes` and `stockout_flag` ship as past-observed
covariates so the model can condition on it. This does not fully correct the
censoring — properly modelling it would mean an explicit censored likelihood —
and that limitation is real and recorded in docs/app_architecture.md.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd
from pytorch_forecasting import TimeSeriesDataSet
from pytorch_forecasting.data import GroupNormalizer, NaNLabelEncoder

# Context the model reads before predicting. 90 days covers a full quarter,
# enough for weekly and monthly structure without making each sample so long
# that short-lived SKUs drop out of training entirely.
MAX_ENCODER_LENGTH = 90

# Matches the app's default forecast horizon (`/forecast-run`'s 30-day option),
# so a trained model serves the most common request without extrapolating past
# what it was trained to produce.
MAX_PREDICTION_LENGTH = 30

TARGET = "sold_qty"
GROUP_ID = "series_id"


@dataclass(frozen=True)
class DatasetBundle:
    """Everything training and evaluation need, built once and shared."""

    training: TimeSeriesDataSet
    validation: TimeSeriesDataSet
    frame: pd.DataFrame
    training_cutoff: int
    validation_cutoff: int


def _add_calendar_features(frame: pd.DataFrame) -> pd.DataFrame:
    """Known-future covariates derivable from the date alone.

    Every column here can be computed for a future date without knowing
    anything about demand, which is what makes them valid known-future inputs
    rather than leakage.
    """
    date = frame["date"]

    frame["day_of_week"] = date.dt.dayofweek.astype(str)
    frame["month"] = date.dt.month.astype(str)
    frame["day_of_month"] = date.dt.day.astype(np.float32)
    frame["week_of_year"] = date.dt.isocalendar().week.astype(np.float32)

    day = date.dt.day
    month = date.dt.month
    days_in_month = date.dt.days_in_month

    # Salaries land at month end in this market and spending clusters around
    # it — a real, publicly known calendar effect, not a seeder artefact.
    frame["is_payday"] = (
        (day >= days_in_month - 2) | (day <= 3)
    ).astype(np.float32)

    # Real Sri Lankan retail festival windows. Dates come from the public
    # calendar, not from the generator's parameters.
    frame["is_avurudu"] = ((month == 4) & day.between(5, 14)).astype(np.float32)
    frame["is_vesak"] = ((month == 5) & day.between(12, 19)).astype(np.float32)
    frame["is_deepavali"] = (
        ((month == 10) & (day >= 25)) | ((month == 11) & (day <= 5))
    ).astype(np.float32)
    frame["is_christmas"] = ((month == 12) & day.between(12, 25)).astype(np.float32)

    return frame


def load_frame(csv_path: str | Path) -> pd.DataFrame:
    """Load the export and engineer every feature the models consume."""
    frame = pd.read_csv(csv_path, parse_dates=["date"])

    if frame.empty:
        raise ValueError(f"{csv_path} contains no rows — run app:export-ml-training-data first")

    frame[GROUP_ID] = (
        frame["warehouse_id"].astype(str) + "-" + frame["sku_id"].astype(str)
    )

    # A contiguous integer day index, shared across every series so that a
    # single cutoff splits them all at the same calendar date.
    epoch = frame["date"].min()
    frame["time_idx"] = (frame["date"] - epoch).dt.days.astype(int)

    frame = _add_calendar_features(frame)

    # Static categoricals must be strings for pytorch-forecasting's encoders.
    for column in ("warehouse_id", "sku_id", "category_id", "brand_id"):
        frame[column] = frame[column].fillna(-1).astype(int).astype(str)

    frame["stockout_minutes"] = frame["stockout_minutes"].astype(np.float32)
    frame["stockout_flag"] = frame["stockout_flag"].astype(np.float32)
    frame["available_qty"] = frame["available_qty"].astype(np.float32)
    frame["received_qty"] = frame["received_qty"].astype(np.float32)
    frame["on_promotion"] = frame["on_promotion"].astype(np.float32)
    frame["promotion_discount"] = frame["promotion_discount"].astype(np.float32)

    # Price spans several orders of magnitude across this catalog (a fan and
    # an air conditioner are not on the same scale); log1p keeps it usable as
    # a static real without one category dominating the encoder.
    frame["log_selling_price"] = np.log1p(
        frame["selling_price"].clip(lower=0).astype(np.float32)
    ).astype(np.float32)

    frame[TARGET] = frame[TARGET].clip(lower=0).astype(np.float32)

    return frame.sort_values([GROUP_ID, "time_idx"]).reset_index(drop=True)


def build_datasets(
    frame: pd.DataFrame,
    *,
    max_encoder_length: int = MAX_ENCODER_LENGTH,
    max_prediction_length: int = MAX_PREDICTION_LENGTH,
    for_deepar: bool = False,
    holdout_days: int | None = None,
    count_target: bool | None = None,
) -> DatasetBundle:
    """Split chronologically and build the training/validation datasets.

    The split is by time, never at random: a random split would let the model
    see a series' future while predicting its past, which inflates every
    metric and is the single most common way a forecasting benchmark lies.

    `for_deepar` switches two things:

    1. **The target normaliser.** DeepAR's negative-binomial likelihood models
       counts directly and requires a non-centred, untransformed target; the
       TFT's quantile loss is happier with a softplus-transformed, per-series
       normalised one.
    2. **Which covariates are available.** DeepAR is autoregressive: it feeds
       its own prediction back in, so pytorch-forecasting requires its encoder
       and decoder to see the same variables and asserts on any mismatch. That
       rules out past-observed covariates entirely — stockouts, stock on hand
       and receipts are unknowable for a future day, so DeepAR gets the target
       alone plus everything known in advance. The TFT has no such limit and
       reads the full set.

       This is not a tuning choice, it is the models' actual capability
       difference, and it is a substantive reason the TFT is the main forecast
       and DeepAR the benchmark: only one of them can condition on the fact
       that last week's zero sales happened during a stockout.
    """
    max_time_idx = int(frame["time_idx"].max())

    if holdout_days is None:
        # Default: hold out the final horizon for testing, and the horizon
        # before it for validation/early stopping. Minimal, but it leaves only
        # one genuinely held-out window to evaluate on.
        validation_cutoff = max_time_idx - max_prediction_length
        training_cutoff = validation_cutoff - max_prediction_length
    else:
        # A longer holdout so evaluation can roll across a full seasonal cycle.
        # This is the only way to measure whether the covariate-aware models
        # actually earn their promotion/festival inputs: those features can
        # only pay off in windows that contain such an event, and a model
        # trained right up to the end of the data has no such window left to be
        # honestly scored on. Costs training data to buy evaluation coverage.
        training_cutoff = max_time_idx - holdout_days
        validation_cutoff = training_cutoff + max_prediction_length

    if training_cutoff <= max_encoder_length:
        raise ValueError(
            "Not enough history to build a training window: need more than "
            f"{max_encoder_length + 2 * max_prediction_length} days, have {max_time_idx + 1}"
        )

    # The normaliser follows the *loss*, not the architecture. A count
    # likelihood (negative binomial) needs an uncentred, untransformed target;
    # quantile loss wants a softplus-transformed one. These default together
    # because DeepAR always uses a count likelihood - but a TFT trained with a
    # count loss needs the count normaliser while keeping the full TFT feature
    # set, so the two are separable.
    if count_target is None:
        count_target = for_deepar

    normalizer = (
        GroupNormalizer(groups=[GROUP_ID], center=False, transformation=None)
        if count_target
        else GroupNormalizer(groups=[GROUP_ID], transformation="softplus")
    )

    training = TimeSeriesDataSet(
        frame[frame["time_idx"] <= training_cutoff],
        time_idx="time_idx",
        target=TARGET,
        group_ids=[GROUP_ID],
        min_encoder_length=max_encoder_length // 2,
        max_encoder_length=max_encoder_length,
        min_prediction_length=1,
        max_prediction_length=max_prediction_length,
        static_categoricals=["warehouse_id", "sku_id", "category_id", "brand_id"],
        static_reals=["log_selling_price"],
        time_varying_known_categoricals=["day_of_week", "month"],
        time_varying_known_reals=[
            "time_idx",
            "day_of_month",
            "week_of_year",
            "is_payday",
            "is_avurudu",
            "is_vesak",
            "is_deepavali",
            "is_christmas",
            "on_promotion",
            "promotion_discount",
        ],
        time_varying_unknown_reals=(
            [TARGET]
            if for_deepar
            else [
                TARGET,
                "stockout_minutes",
                "stockout_flag",
                "available_qty",
                "received_qty",
            ]
        ),
        target_normalizer=normalizer,
        # A SKU that launches after the training cutoff appears in validation
        # as a category the encoder has never seen, which is a hard error by
        # default. add_nan lets it map to an "unknown" bucket instead of
        # crashing the split. Note that a genuinely new SKU still has no
        # learned embedding and so gets no useful neural forecast — that is
        # the cold-start case, and Laravel already routes it through
        # DemandProfileService's peer hierarchy rather than the model.
        categorical_encoders={
            GROUP_ID: NaNLabelEncoder(add_nan=True),
            "warehouse_id": NaNLabelEncoder(add_nan=True),
            "sku_id": NaNLabelEncoder(add_nan=True),
            "category_id": NaNLabelEncoder(add_nan=True),
            "brand_id": NaNLabelEncoder(add_nan=True),
        },
        add_relative_time_idx=True,
        add_target_scales=True,
        add_encoder_length=True,
        allow_missing_timesteps=True,
    )

    validation = TimeSeriesDataSet.from_dataset(
        training,
        frame[frame["time_idx"] <= validation_cutoff],
        predict=True,
        stop_randomization=True,
    )

    return DatasetBundle(
        training=training,
        validation=validation,
        frame=frame,
        training_cutoff=training_cutoff,
        validation_cutoff=validation_cutoff,
    )


def build_test_dataset(bundle: DatasetBundle) -> TimeSeriesDataSet:
    """The final held-out horizon — never seen during training or early stopping."""
    return TimeSeriesDataSet.from_dataset(
        bundle.training,
        bundle.frame,
        predict=True,
        stop_randomization=True,
    )
